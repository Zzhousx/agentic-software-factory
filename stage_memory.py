"""Evolution-task memory (935.V1).

Staged tasks say: "Extend the application generated by the previous stage when available; otherwise start from the
provided blank application template. Only this stage's tests are executed." The platform's tests for stage N sign in,
open repositories, etc. through features that stage N-1 built, so those features must keep working while stage N is
added. In the 932.V1 runs of a three-stage task:
  * stage 2 inherited stage 1's application, but its plan was made without looking at it (the planning call also timed
    out), and 5 of its own tests could not find the sign-in control the earlier stage had provided;
  * nothing checked earlier-stage behaviour, because the earlier stage's acceptance specs lived in .arc/, which the
    runtime's .gitignore excludes from the project snapshot.

This module keeps a small, committed project folder (FOLDER) with
  acceptance/  this stage's requirement-derived Playwright specs (written by acceptance.SpecGenerator),
  legacy/      the specs of all earlier stages (moved here when a later stage starts on the inherited project),
  history/     the requirement trees of earlier stages (for repair prompts and the plan),
  plan.json    the last architecture plan.
On an inherited project the earlier specs are run once against the inherited application; the passing ones guard every
later change exactly like this stage's own passing tests (tdd_loop.AcceptanceLoop).

Everything is derived from the supplied requirements and our own generated files; no product vocabulary.
"""
from __future__ import annotations

import json
import re
import shutil
from pathlib import Path

FOLDER = 'evogit'
_REF = re.compile(r'\b(REQ-[0-9]+(?:[-.][0-9]+)*)\s*\(([^()]{3,120})\)')
README = """# evogit project memory

Written by the generation agent; not used by the application at runtime.

- `acceptance/` - Playwright specs derived from this stage's requirements (the agent's own acceptance tests).
- `legacy/` - the specs of earlier stages of an evolving project, used as regression guards.
- `history/` - requirement trees of earlier stages.
- `plan.json` - the architecture plan the code was generated from.
"""


def memory_dir(root) -> Path:
    return Path(root) / FOLDER


def _walk(node):
    if not isinstance(node, dict):
        return []
    out = [node]
    for child in node.get('children') or []:
        out.extend(_walk(child))
    return out


def _ids(document) -> set[str]:
    return {str(n.get('id')) for n in _walk(document) if n.get('id') is not None}


def _leaf_nodes(document) -> dict[str, dict]:
    return {str(n.get('id')): n for n in _walk(document)
            if n.get('id') is not None and not [c for c in n.get('children') or [] if isinstance(c, dict)]}


def _compact(node):
    """Requirement tree without screenshots/binary noise (kept small enough to commit)."""
    if not isinstance(node, dict):
        return node
    out = {k: node[k] for k in ('id', 'name', 'type', 'description', 'dependencies', 'scenarios') if k in node}
    children = [_compact(c) for c in node.get('children') or [] if isinstance(c, dict)]
    if children:
        out['children'] = children
    return out


def _read_specs(folder: Path) -> dict[str, str]:
    if not folder.is_dir():
        return {}
    return {p.name: p.read_text(encoding='utf-8', errors='replace') for p in sorted(folder.glob('*.spec.ts'))}


def _strings(node):
    if isinstance(node, str):
        yield node
    elif isinstance(node, dict):
        for value in node.values():
            yield from _strings(value)
    elif isinstance(node, list):
        for value in node:
            yield from _strings(value)


def missing_prerequisites(document, known: dict[str, dict] | None = None) -> list[dict]:
    """Requirement ids this document depends on or refers to ("builds on REQ-1-1-2 (Sign In ...)") without defining
    them: features of earlier stages. Each row: id, name, and the earlier stage's description when known."""
    defined = _ids(document)
    names: dict[str, str] = {}
    for text in _strings(document):
        for req_id, name in _REF.findall(text):
            if req_id not in defined:
                names.setdefault(req_id, ' '.join(name.split()))
    for node in _walk(document):
        for dep in node.get('dependencies') or []:
            if str(dep) not in defined:
                names.setdefault(str(dep), '')
    rows = []
    for req_id in sorted(names, key=lambda r: [int(x) if x.isdigit() else 0 for x in re.split(r'[-.]', r[4:])]):
        node = (known or {}).get(req_id) or {}
        rows.append({'id': req_id, 'name': names[req_id] or str(node.get('name') or ''),
                     'description': ' '.join(str(node.get('description') or '').split())[:1500]})
    return rows


def prerequisites_text(rows: list[dict], inherited: bool, limit: int = 6000) -> str:
    rows = [row for row in rows or [] if row.get('name') or row.get('description')]   # a bare id tells the model nothing
    if not rows:
        return ''
    lines = []
    for row in rows:
        line = f"- {row['id']}" + (f" {row['name']}" if row['name'] else '')
        if row.get('description'):
            line += ': ' + row['description']
        lines.append(line)
    head = ('These requirements of EARLIER STAGES are referenced by this stage but not specified in it. The inherited '
            'application already provides them: keep them working exactly as they are (same routes, controls, names, '
            'seed accounts) and build the new features on them.' if inherited else
            'These requirements of EARLIER STAGES are referenced by this stage but not specified in it, and no earlier '
            'application was inherited: the application must still provide them (the flows the new scenarios rely on, '
            'e.g. signing in with the seeded accounts), following the wording this stage uses for them.')
    return (head + '\n' + '\n'.join(lines))[:limit]


def load(root, document, inherited: bool) -> dict:
    """Prepare the memory folder at the start of a run and return what earlier stages left behind."""
    root = Path(root)
    mem = memory_dir(root)
    info = {'inherited': bool(inherited), 'legacy_specs': {}, 'legacy_leaves': {}, 'previous_plan': None,
            'previous_outline': '', 'history_stages': 0, 'prerequisites': []}
    if not inherited:
        # A fresh project: anything left here belongs to another application.
        shutil.rmtree(mem, ignore_errors=True)
        info['prerequisites'] = missing_prerequisites(document)
        return info
    current = _ids(document)
    legacy: dict[str, str] = {}
    # Older generations first; a newer stage's spec of the same name wins.
    for folder in (mem / 'legacy', root / '.arc' / 'acceptance', mem / 'acceptance'):
        legacy.update(_read_specs(folder))
    legacy = {name: content for name, content in legacy.items() if name[:-len('.spec.ts')] not in current}
    history = []
    for path in sorted((mem / 'history').glob('*.json')) if (mem / 'history').is_dir() else []:
        try:
            history.append(json.loads(path.read_text(encoding='utf-8')))
        except (OSError, ValueError):
            continue
    known: dict[str, dict] = {}
    outline_rows = []
    for entry in history:
        doc = entry.get('document') if isinstance(entry, dict) else None
        for node in _walk(doc):
            node_id = str(node.get('id')) if node.get('id') is not None else ''
            if node_id and node_id not in current and node_id != 'ROOT':
                known[node_id] = node
                outline_rows.append(f"- {node_id}: {node.get('name', '')}")
    plan = None
    for candidate in (mem / 'plan.json', root / 'IMPLEMENTATION_PLAN.json'):
        try:
            data = json.loads(candidate.read_text(encoding='utf-8'))
        except (OSError, ValueError):
            continue
        if isinstance(data, dict) and isinstance(data.get('architecture'), str) and not data.get('fallback'):
            plan = data
            break
    # Reorganise on disk: legacy/ holds every earlier spec, acceptance/ is reserved for this stage.
    (mem / 'legacy').mkdir(parents=True, exist_ok=True)
    for name, content in legacy.items():
        (mem / 'legacy' / name).write_text(content, encoding='utf-8')
    shutil.rmtree(mem / 'acceptance', ignore_errors=True)
    leaves = {}
    for entry in history:
        doc = entry.get('document') if isinstance(entry, dict) else None
        leaves.update({k: v for k, v in _leaf_nodes(doc).items() if k not in current})
    info.update(legacy_specs=legacy, legacy_leaves=leaves, previous_plan=plan,
                previous_outline='\n'.join(dict.fromkeys(outline_rows))[:8000], history_stages=len(history),
                prerequisites=missing_prerequisites(document, known))
    return info


def record_stage(root, document) -> None:
    """Add this stage's requirement tree to history/ (replacing an earlier record of the same requirement set)."""
    hist = memory_dir(root) / 'history'
    hist.mkdir(parents=True, exist_ok=True)
    ids = sorted(_ids(document))
    for path in hist.glob('*.json'):
        try:
            if sorted(_ids(json.loads(path.read_text(encoding='utf-8')).get('document'))) == ids:
                path.unlink()
        except (OSError, ValueError, AttributeError):
            continue
    number = len(list(hist.glob('*.json'))) + 1
    payload = {'stage': number, 'name': str(document.get('name') or '') if isinstance(document, dict) else '',
               'document': _compact(document)}
    (hist / f'stage-{number:02d}.json').write_text(json.dumps(payload, ensure_ascii=False, indent=1), encoding='utf-8')
    readme = memory_dir(root) / 'README.md'
    if not readme.exists():
        readme.write_text(README, encoding='utf-8')


def save_plan(root, plan) -> None:
    if not isinstance(plan, dict) or plan.get('fallback'):
        return
    mem = memory_dir(root)
    mem.mkdir(parents=True, exist_ok=True)
    (mem / 'plan.json').write_text(json.dumps(plan, ensure_ascii=False, indent=1), encoding='utf-8')


def spec_store(root) -> Path:
    return memory_dir(root) / 'acceptance'


def existing_application_text(root, info: dict, surface: str, limit: int = 16000) -> str:
    """What the architecture step must know about an inherited application."""
    parts = []
    files = []
    for part in ('frontend/src', 'backend/src'):
        base = Path(root) / part
        if base.exists():
            for path in sorted(base.rglob('*')):
                if path.is_file():
                    files.append(f"{path.relative_to(root).as_posix()} ({path.stat().st_size} B)")
    if files:
        parts.append('SOURCE FILES OF THE EXISTING APPLICATION:\n' + '\n'.join(files[:160]))
    if surface:
        parts.append('ITS IMPLEMENTATION SURFACE:\n' + surface)
    plan = info.get('previous_plan') or {}
    if plan.get('architecture'):
        parts.append('PLAN OF THE PREVIOUS STAGE (excerpt; the code above follows it):\n' + plan['architecture'][:9000] +
                     ('\nPRODUCT CONVENTIONS USED: ' + str(plan.get('conventions'))[:3000] if plan.get('conventions') else ''))
    if info.get('previous_outline'):
        parts.append('REQUIREMENTS IMPLEMENTED BY EARLIER STAGES:\n' + info['previous_outline'])
    return '\n\n'.join(parts)[:limit]
